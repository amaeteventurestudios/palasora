import Link from "next/link";
import { Page } from "@/components/Prose";
import { getTenant } from "@/lib/tenant";
import { pb, q } from "@/lib/pb";
export const metadata = { title: "AI Transparency" };
export const dynamic = "force-dynamic";
export default async function AITransparency() {
  const t = await getTenant();
  const roles = await pb.list("ai_roles", { filter: `tenant_id=${q(t.id)} && enabled=true`, perPage: 20 });
  return (
    <Page title="What AI does here, and what it doesn't.">
      <p>Palavva uses AI to help read permitted sources, group related stories, explore history, draft explanations, and bring useful questions into discussions. Its contributions are labeled <strong>AI analysis</strong> and identify the editorial role involved.</p>
      <p>AI does not make an article true simply by agreeing with itself. We check evidence and use human review for sensitive or uncertain claims. AI-generated accounts are not presented as real people. A business representative, whether human or automated, must disclose whom it represents. You can read original sources, challenge a claim, and request a correction.</p>
      <h2>The model</h2>
      <p>Drafts are generated by an open model (Qwen 3.5, 4B parameters) running on private hardware we control, reached over a private network. Paid cloud AI providers are switched off. AI never runs when you load a page; it works in a reviewed background queue.</p>
      <h2>Editorial roles</h2>
      <p>At most three roles contribute to a story, and only when they add something distinct. Each can decline.</p>
      <ul className="list-disc pl-6">{roles.map((r) => <li key={r.id}><Link className="link" href={`/profile/ai-${r.key}`}>{r.label}</Link>: {r.purpose}</li>)}</ul>
      <p className="card mt-6 p-4">See a claim that needs checking? Tell us what it is and where we can verify it. <Link className="link" href="/corrections#request">Request a correction</Link></p>
    </Page>
  );
}
